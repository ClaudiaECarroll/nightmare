"""
Run the Python BookNLP pipeline on Dialogism plain-text novels.

Input:  ../../data/raw/texts/*.txt   (generated by extract_plain_text.py)
Output: ../../data/intermediate/BookNLP_output/<book>/<book>.quotes
                                                        /<book>.tokens
                                                        ...

The "small" model is used — accurate for quote detection and tractable on a laptop.
On first run, BookNLP downloads its models (~hundreds of MB) into ~/booknlp_models.
"""

import os
import glob
import sys
import warnings
warnings.filterwarnings("ignore")

import torch

# Drop legacy state-dict keys that break modern transformers (same fix as take3).
_orig_torch_load = torch.load

def _torch_load_drop_legacy(*args, **kwargs):
    state = _orig_torch_load(*args, **kwargs)
    if isinstance(state, dict):
        for key in [k for k in state
                    if k.endswith("position_ids") or k.endswith("token_type_ids")]:
            state.pop(key)
    return state

torch.load = _torch_load_drop_legacy

HERE        = os.path.dirname(os.path.abspath(__file__))
TEXTS_DIR   = os.path.join(HERE, "..", "..", "..", "data", "raw", "texts")
OUTPUT_ROOT = os.path.join(HERE, "..", "..", "..", "data", "intermediate", "BookNLP_output")

MODEL_PARAMS = {
    "pipeline": "entity,quote,coref",
    "model":    "small",
}


def already_done(output_dir, book_id):
    quotes_path = os.path.join(output_dir, book_id + ".quotes")
    if not os.path.exists(quotes_path):
        return False
    with open(quotes_path, "r", encoding="utf-8") as fh:
        fh.readline()
        return bool(fh.readline())


def main():
    from booknlp.booknlp import BookNLP

    model = BookNLP("en", MODEL_PARAMS)

    os.makedirs(OUTPUT_ROOT, exist_ok=True)
    input_files = sorted(glob.glob(os.path.join(TEXTS_DIR, "*.txt")))
    print(f"Found {len(input_files)} text files in {TEXTS_DIR}\n")

    for i, input_file in enumerate(input_files, start=1):
        book_id    = os.path.splitext(os.path.basename(input_file))[0]
        output_dir = os.path.join(OUTPUT_ROOT, book_id)

        if already_done(output_dir, book_id):
            print(f"[{i}/{len(input_files)}] {book_id}: already done, skipping")
            continue

        os.makedirs(output_dir, exist_ok=True)
        print(f"[{i}/{len(input_files)}] processing {book_id} ...", flush=True)
        try:
            model.process(input_file, output_dir, book_id)
        except Exception as e:
            print(f"    !! failed on {book_id}: {e}", file=sys.stderr)

    print("Done.")


if __name__ == "__main__":
    main()
